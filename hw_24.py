# Вычисляем максимальное кол-во возможных уникальных комбинаций
MAX_COMBINATIONS = len(proverbs) * len(variants)

# Ввод данных и проверка
user_input = input(f"Сколько пословиц сгенерировать? (1-{MAX_COMBINATIONS}): ")

# Проверка на отрицательное число
if user_input.startswith("-"):
    print("Ошибка: количество должно быть положительным!")
    exit()

if not user_input.isdigit():
    print("Ошибка: нужно ввести число!")
    exit()

requested = int(user_input)

if requested <= 0:
    print("Ошибка: количество должно быть положительным!")
    exit()

if requested > MAX_COMBINATIONS:
    print(
        f"Ошибка: нельзя сгенерировать больше {MAX_COMBINATIONS} уникальных пословиц!"
    )
    exit()

# Проверка лимита до входа в цикл while
results = []

while len(results) < requested:
    random_proverb = random.choice(proverbs)
    random_variant = random.choice(variants)

    new_proverb = random_proverb.replace("Ум", random_variant)

    if new_proverb not in results:
        results.append(new_proverb)

print("\nСгенерированные пословицы:")
for i, proverb in enumerate(results, 1):
    print(f"{i}. {proverb}")
