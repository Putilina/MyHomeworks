#  ПОЛУЧЕНИЕ И ПРОВЕРКА ВВОДА


def get_validated_count() -> int:
    """
    Запрашивает у пользователя количество пословиц и выполняет валидацию.

    Проверки:
        1. Ввод не пустой
        2. Ввод состоит только из цифр
        3. Число больше нуля

    Returns:
        int: Проверенное количество пословиц (целое положительное число)

    Note:
        При любой ошибке ввода программа завершается через exit()
    """
    user_input = input("Сколько пословиц сгенерировать? ")

    # Проверяем являются ли все символы цифрами
    if not user_input.isdigit():
        print(" ОШИБКА: Нужно ввести целое положительное число!")
        exit()

    # Преобразование в число
    count = int(user_input)

    # Проверяем больше ли нуля
    if count <= 0:
        print(" ОШИБКА: Число должно быть больше нуля!")
        exit()

    return count


# ГЕНЕРАЦИЯ ВСЕХ КОМБИНАЦИЙ


def create_all_combinations(proverbs_set: set[str], variants_set: set[str]) -> set[str]:
    """
    Генерирует все возможные комбинации пословиц и вариантов замены.

    Как работает:
    - Внешний цикл: перебирает каждую пословицу
    - Внутренний цикл: перебирает каждый вариант
    - Заменяет слово "Ум" на вариант
    - Добавляет результат в множество

    Args:
        proverbs_set: Множество исходных пословиц
        variants_set: Множество вариантов для замены

    Returns:
        set[str]: Множество всех уникальных комбинаций

    Пример:
        proverbs_set = {"Ум хорош", "Ум велик"}
        variants_set = {"кот", "пёс"}
    """
    all_combinations = set()

    # Внешний цикл: перебираем все пословицы
    for proverb in proverbs_set:
        # Внутренний цикл: перебираем все варианты
        for variant in variants_set:
            # Заменяем "Ум" на вариант и добавляем в множество
            new_proverb = proverb.replace("Ум", variant)
            all_combinations.add(new_proverb)

    return all_combinations


# ФУНКЦИЯ 3: ВЫБОРКА НУЖНОГО КОЛИЧЕСТВА


def pick_items(source_set: set[str], count: int) -> set[str]:
    """
    Выбирает указанное количество случайных элементов из множества.

    Использует метод .pop(), который:
        1. Берёт случайный элемент (т.к. множество неупорядочено)
        2. Удаляет его из исходного множества
        3. Возвращает этот элемент

    Это гарантирует, что каждый элемент будет выбран только один раз!

    Args:
        source_set (set[str]): Исходное множество (будет изменено!)
        count (int): Сколько элементов нужно выбрать

    Returns:
        set[str]: Множество выбранных уникальных элементов

    Note:
        Исходное множество source_set уменьшится на count элементов
    """
    selected = set()

    # Цикл продолжается, пока не набрали нужное количество
    while len(selected) < count:
        # pop() удаляет и возвращает случайный элемент
        item = source_set.pop()
        selected.add(item)

    return selected


# ФУНКЦИЯ 4: ВЫВОД РЕЗУЛЬТАТОВ (ОБЫЧНЫЙ)


def print_results(results_set: set[str]) -> None:
    """
    Выводит пронумерованный список пословиц в консоль.

    Args:
        results_set (set[str]): Множество пословиц для вывода

    Note:
        Нумерация выполняется через ручной счётчик
    """
    print("\n" + "=" * 70)
    print(" " * 25 + "РЕЗУЛЬТАТ ГЕНЕРАЦИИ")
    print("=" * 70)

    # Ручной счётчик
    counter = 0

    for proverb in results_set:
        counter += 1
        print(f"{counter:3}. {proverb}")

    print("=" * 70 + "\n")


#  ВЫВОД РЕЗУЛЬТАТОВ


def print_table(results_set: set[str]) -> None:
    """
    Args:
        results_set (set[str]): Множество пословиц для вывода

    """

    # Подготовка данных для таблицы
    table_data = []
    counter = 0

    for proverb in results_set:
        counter += 1
        table_data.append([counter, proverb])

    # Вывод таблицы
    print(
        "\n" + tabulate(table_data, headers=["№", "Пословица"], tablefmt="grid") + "\n"
    )


