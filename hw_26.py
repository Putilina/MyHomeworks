    print("Проверка ввода пользователя...")
    requested_count = get_validated_count()
    print(f"  Запрошено пословиц: {requested_count}")

    print("  Генерация всех возможных комбинаций...")
    print(" (Выполняется декартово произведение множеств)")
    all_combinations = create_all_combinations(proverbs, variants)

    total_available = len(all_combinations)
    print(f"  Всего сгенерировано: {total_available} уникальных пословиц")
    print(f"  (Формула: {len(proverbs)} × {len(variants)} = {total_available})")

    if requested_count > total_available:
        print(" ОШИБКА: Запрошенное количество превышает доступное!")
        print(f"  Запрошено: {requested_count}")
        print(f"  Доступно: {total_available}")
        print("   Попробуйте снова с меньшим числом.")
        exit()

    print(f" Выборка {requested_count} случайных пословиц...")
    print("  (Используется метод .pop() для безвозвратного извлечения)")
    selected_proverbs = pick_items(all_combinations, requested_count)

    # ===== ВЫВОД РЕЗУЛЬТАТА =====
    print(" Вывод результата:")

    # Выбираем способ вывода (таблица или обычный список)
    if TABULATE_AVAILABLE:
        print_table(selected_proverbs)
    else:
        print_results(selected_proverbs)

    print("✅ Программа успешно завершена!")


